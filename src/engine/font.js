  var glyphs = {};
  for (var ch in RAW) {
    var rows = RAW[ch];
    glyphs[ch] = { w: rows[0].length, rows: rows };
  }
  var cache = {};

  function glyphCanvas(ch, color) {
    var key = color + ch;
    var c = cache[key];
    if (c) return c;
    var g = glyphs[ch] || glyphs['?'];
    c = PK.makeCanvas(g.w, 9);
    var x = c.getContext('2d');
    x.fillStyle = color;
    for (var r = 0; r < g.rows.length; r++) {
      var row = g.rows[r];
      for (var i = 0; i < row.length; i++) if (row[i] === '#') x.fillRect(i, r, 1, 1);
    }
    cache[key] = c;
    return c;
  }

  function charW(ch) {
    var g = glyphs[ch] || glyphs['?'];
    return g.w + 1;
  }

  PK.font = {
    height: 7,
    width: function (str) {
      str = String(str);
      var w = 0;
      for (var i = 0; i < str.length; i++) w += charW(str[i]);
      return w ? w - 1 : 0;
    },
    // Draw text; optional shadow color drawn right/down.
    draw: function (ctx, str, x, y, color, shadow, scale) {
      str = String(str);
      scale = scale || 1;
      x = Math.round(x); y = Math.round(y);
      if (shadow) {
        this._raw(ctx, str, x + scale, y, shadow, scale);
        this._raw(ctx, str, x, y + scale, shadow, scale);
        this._raw(ctx, str, x + scale, y + scale, shadow, scale);
      }
      this._raw(ctx, str, x, y, color || '#383848', scale);
    },
    _raw: function (ctx, str, x, y, color, scale) {
      var cx = x;
      for (var i = 0; i < str.length; i++) {
        var ch = str[i];
        var g = glyphs[ch] || glyphs['?'];
        if (ch !== ' ') {
          var c = glyphCanvas(ch, color);
          if (scale === 1) ctx.drawImage(c, cx, y);
          else ctx.drawImage(c, cx, y, c.width * scale, c.height * scale);
        }
        cx += (g.w + 1) * scale;
      }
    },
    // Outlined text (for titles / overlays)
    outline: function (ctx, str, x, y, color, outlineColor, scale) {
      scale = scale || 1;
      for (var dy = -1; dy <= 1; dy++)
        for (var dx = -1; dx <= 1; dx++)
          if (dx || dy) this._raw(ctx, str, x + dx * scale, y + dy * scale, outlineColor, scale);
      this._raw(ctx, str, x, y, color, scale);
    },
    center: function (ctx, str, cx, y, color, shadow, scale) {
      this.draw(ctx, str, Math.round(cx - this.width(str) * (scale || 1) / 2), y, color, shadow, scale);
    },
    right: function (ctx, str, rx, y, color, shadow) {
      this.draw(ctx, str, rx - this.width(str), y, color, shadow);
    },
    wrap: function (text, maxW) {
      var out = [];
      var paras = String(text).split('\n');
      for (var p = 0; p < paras.length; p++) {
        var words = paras[p].split(' ');
        var line = '';
        for (var i = 0; i < words.length; i++) {
          var test = line ? line + ' ' + words[i] : words[i];
          if (this.width(test) > maxW && line) { out.push(line); line = words[i]; }
          else line = test;
        }
        out.push(line);
      }
      return out;
    }
  };
